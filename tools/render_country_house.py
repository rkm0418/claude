#!/usr/bin/env python3
"""가을 세계의 집 안: 평범한 가정집을 가로로 길게 자른 단면(방 | 거실 | 부엌·식탁). 사선 3차원 시점(도시·시골과 같은 투영).
시골 티를 빼고 흔한 집처럼: 나무 마루, 무난한 벽지, 커튼 창, 침대·소파·텔레비전·식탁·냉장고. 칸막이벽에 출입구(문틀)가 있어 방끼리 이어진다.
사용: python3 tools/render_country_house.py -> maps/out/country_house.png (+_x4)"""
import math, os, random, sys
from PIL import Image, ImageDraw
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
from render_city3d import Scene, dk, OUT

def noise(x, d, s=0): return ((int(x * 12.9898 + d * 78.233 + s * 37.7) * 2654435761) >> 7) % 100 / 100.0
W, D, H = 216, 64, 58
RX = (0, 72, 144, 216)                                       # 방 경계(x)
WALLC = ((206, 214, 222), (232, 218, 186), (206, 224, 204))   # 방별 벽지: 연한 청회색 / 크림 / 연한 연두
WOOD, WOOD_D = (150, 104, 66), (108, 72, 46)

def build():
    sc = Scene(W, D, H); sc.img.paste((30, 22, 24), (0, 0, sc.CW, sc.CH)); sc.d = ImageDraw.Draw(sc.img)
    def front(x0, x1, z0, z1, col, d=D): sc.poly([(x0, d, z0), (x1, d, z0), (x1, d, z1), (x0, d, z1)], col)
    def left(d0, d1, z0, z1, col, x=0): sc.poly([(x, d0, z0), (x, d1, z0), (x, d1, z1), (x, d0, z1)], col)
    def room_of(x): return 0 if x < RX[1] else 1 if x < RX[2] else 2
    # 바닥: 방과 거실은 나무 마루(가로 판), 부엌은 베이지 타일
    def floor(x, d):
        r = room_of(x); n = noise(x, d)
        if r == 2:
            return (200, 190, 170) if (x % 12 < 1 or d % 12 < 1) else ((226, 218, 198) if ((int(x // 12) + int(d // 12)) % 2) else (216, 208, 188))
        base = (172 + int(n * 8), 122 + int(n * 8), 78 + int(n * 6)); 
        if d % 11 < .8: return (122, 84, 52)
        if noise(int(x // 30), int(d // 11), 2) < .5 and x % 30 < .8: return (122, 84, 52)
        return base
    sc.floor(floor)
    sc.poly([(0, 0, -6), (W, 0, -6), (W, 0, 0), (0, 0, 0)], (90, 62, 40)); sc.poly([(W, 0, -6), (W, D, -6), (W, D, 0), (W, 0, 0)], (66, 44, 30))
    # 뒤쪽 벽: 방별 벽지 + 걸레받이 + 윗띠, 왼쪽 바깥벽
    for r in range(3):
        a, b = RX[r], RX[r + 1]; c = WALLC[r]
        front(a, b, 0, H, c); front(a, b, 0, 5, (236, 232, 224)); front(a, b, H - 4, H, dk(c, .8))
        for xx in range(a + 3, b, 12): front(xx, xx + .8, 6, H - 5, dk(c, .94))
    left(0, D, 0, H, WALLC[0]); left(0, D, 0, 5, (236, 232, 224)); left(0, D, H - 4, H, dk(WALLC[0], .8))
    # 칸막이벽(출입구 포함): 오른쪽 면이 보인다. 앞 끝 단면이 보이도록 두께 4
    def partition(a, d0, d1):
        c = WALLC[room_of(a + 5)]
        for (x0, w, dd0, dd1, z0, z1) in ((a, 4, 0, d0, 0, H), (a, 4, d1, D, 0, H), (a, 4, d0, d1, 44, H)):
            sc.box(x0, dd0, w, dd1 - dd0, z1 - z0, dk(c, .8), dk(c, .98), dk(c, .88), z0=z0)
        for z0, z1, col in ((0, 5, (236, 232, 224)),):
            sc.poly([(a + 4, 0, z0), (a + 4, d0, z0), (a + 4, d0, z1), (a + 4, 0, z1)], col); sc.poly([(a + 4, d1, z0), (a + 4, D, z0), (a + 4, D, z1), (a + 4, d1, z1)], col)
        sc.poly([(a + 4, d0, 0), (a + 4, d1, 0), (a + 4, d1, 44), (a + 4, d0, 44)], (24, 20, 18))     # 출입구 안쪽(다음 방으로 이어지는 어둠 말고 문틀)
        for (p, q, z0, z1) in ((d0 - 1.5, d0, 0, 45), (d1, d1 + 1.5, 0, 45), (d0 - 1.5, d1 + 1.5, 44, 45.5)):
            sc.poly([(a + 4.1, p, z0), (a + 4.1, q, z0), (a + 4.1, q, z1), (a + 4.1, p, z1)], (240, 236, 226))
    partition(RX[1] - 4, 22, 42); partition(RX[2] - 4, 22, 42)
    # ----- 가구 -----
    # 방 1: 창, 침대, 협탁+스탠드, 옷장
    left(14, 40, 18, 46, (244, 240, 230)); left(15.5, 38.5, 19.5, 44.5, (176, 206, 226)); left(14, 40, 18, 19.2, (244, 240, 230))
    left(13, 21, 17, 47, (196, 120, 110)); left(33, 41, 17, 47, (196, 120, 110))                              # 커튼
    sc.glow(6, 27, 40, col=(255, 214, 150), power=.35)
    sc.box(10, 20, 36, 40, 10, (232, 236, 240), (232, 236, 240), (232, 236, 240), z0=0) if False else None
    sc.box(8, 24, 36, 40, 8, (130, 96, 70), (146, 108, 76), (104, 76, 54))                                  # 침대 프레임
    sc.box(9, 25, 34, 38, 4, (210, 224, 238), (190, 206, 224), (160, 178, 200), z0=8)                         # 이불
    sc.box(10, 54, 14, 8, 3, (246, 246, 244), (226, 226, 224), (196, 196, 194), z0=12)                       # 베개
    sc.box(46, 52, 12, 10, 14, (140, 100, 70), (154, 112, 78), (112, 80, 54)); sc.box(50, 55, 4, 4, 3, (244, 230, 170), (244, 230, 170), (210, 196, 140), z0=14)   # 협탁+스탠드
    sc.box(40, D - 14, 18, 14, 44, (134, 96, 66), (150, 108, 74), (108, 76, 52)); front(42, 49, 4, 42, (118, 82, 56), d=D - 14.2); front(50, 57, 4, 42, (118, 82, 56), d=D - 14.2)
    front(48.2, 49, 20, 26, (214, 190, 120), d=D - 14.4); front(50, 50.8, 20, 26, (214, 190, 120), d=D - 14.4)
    # 방 2(거실): 뒤쪽 큰 창과 커튼, 소파, 텔레비전, 탁자, 스탠드, 화분
    front(90, 122, 18, 48, (244, 240, 230)); front(91.5, 120.5, 19.5, 46.5, (240, 190, 130)); front(105.6, 106.4, 19.5, 46.5, (244, 240, 230))
    for xa in (86, 118): front(xa, xa + 8, 16, 49, (150, 170, 150))
    sc.glow(106, D - 4, 36, col=(255, 200, 120), power=.3, z=20)
    sc.box(80, 34, 40, 14, 10, (126, 140, 160), (140, 154, 174), (100, 112, 130)); sc.box(80, 46, 40, 5, 20, (118, 132, 152), (132, 146, 166), (96, 108, 126))   # 소파
    sc.box(124, D - 14, 18, 14, 9, (140, 100, 70), (154, 112, 78), (112, 80, 54)); sc.box(126, D - 12, 14, 8, 12, (50, 52, 56), (62, 64, 70), (40, 42, 46), z0=9); front(128, 138, 11, 19, (26, 34, 32), d=D - 12.2)   # TV
    sc.box(92, 18, 20, 12, 5, (150, 108, 72), (164, 120, 82), (120, 86, 58))                                  # 거실 탁자
    sc.box(78, D - 6, 2, 2, 28, (80, 70, 60), (80, 70, 60), (60, 52, 44)); sc.box(74, D - 8, 10, 6, 6, (248, 240, 206), (248, 240, 206), (216, 208, 176), z0=28)   # 플로어 스탠드
    sc.box(130, 8, 6, 6, 8, (160, 100, 70), (176, 112, 78), (130, 82, 58)); sc.box(128, 6, 10, 10, 12, (70, 130, 84), (84, 148, 98), (54, 104, 66), z0=8)    # 화분
    # 방 3(부엌): 냉장고, 싱크대, 창, 식탁과 의자, 펜던트 전구
    sc.box(196, D - 14, 16, 14, 50, (236, 238, 240), (222, 224, 228), (190, 192, 198)); front(197, 211, 26, 27, (170, 172, 180), d=D - 14.2); front(209, 210, 29, 40, (140, 142, 150), d=D - 14.3); front(209, 210, 9, 20, (140, 142, 150), d=D - 14.3)
    sc.box(150, D - 14, 44, 14, 22, (206, 196, 176), (226, 216, 194), (170, 160, 142)); sc.box(150, D - 14, 44, 14, 2, (176, 180, 188), (176, 180, 188), (150, 154, 162), z0=22)   # 싱크대 + 상판
    sc.box(160, D - 11, 14, 8, 1, (130, 136, 146), (130, 136, 146), (110, 116, 126), z0=24); sc.box(170, D - 7, 1.5, 1.5, 6, (160, 164, 172), (160, 164, 172), (140, 144, 152), z0=24)   # 개수대+수도꼭지
    front(158, 180, 30, 50, (244, 240, 230)); front(159.5, 178.5, 31.5, 48.5, (232, 214, 170)); front(168.3, 169.2, 31.5, 48.5, (244, 240, 230))     # 부엌 창
    def chair(x, d, far):
        sc.box(x, d, 8, 8, 10, (190, 150, 100), (204, 162, 108), (150, 116, 76)); sc.box(x, d + (6 if far else 0), 8, 2, 13, (176, 138, 92), (190, 150, 100), (140, 106, 70), z0=10)
    chair(162, 38, True); chair(178, 38, True)
    sc.box(158, 18, 30, 18, 3, (176, 122, 80), (190, 134, 90), (140, 96, 62), z0=17)
    for x in (160, 184):
        for d in (20, 32): sc.box(x, d, 2, 2, 17, WOOD_D, WOOD_D, WOOD_D)
    chair(162, 6, False); chair(178, 6, False)
    sc.box(166, 24, 6, 6, 2, (240, 236, 226), (230, 226, 216), (200, 196, 186), z0=20); sc.box(176, 26, 4, 4, 3, (206, 90, 70), (190, 80, 62), (150, 62, 48), z0=20)   # 식탁 위 접시·주전자
    # 천장 전구(방마다 하나): 줄 + 전구 + 바닥 빛
    for cx, col in ((36, (255, 226, 160)), (108, (255, 226, 160)), (172, (255, 230, 170))):
        b = sc.P(cx, 34, H - 6); sc.d.line([(b[0], max(0, b[1] - 12)), (b[0], b[1] - 2)], fill=(40, 34, 30)); sc.d.rectangle([b[0] - 2, b[1] - 2, b[0] + 2, b[1] + 3], fill=col)
        sc.glow(cx, 34, 52, col=col, power=.38)
    ov = Image.new('RGB', sc.img.size, (255, 200, 130)); sc.img = Image.blend(sc.img, ov, .04)
    return sc

def main():
    sc = build(); out = os.path.join(OUT, 'country_house.png'); sc.img.save(out)
    sc.img.resize((sc.CW * 4, sc.CH * 4), Image.NEAREST).save(out.replace('.png', '_x4.png')); sc.img.resize((sc.CW * 3, sc.CH * 3), Image.NEAREST).save(out.replace('.png', '_x3.png')); print(out, sc.img.size)
if __name__ == '__main__': main()
